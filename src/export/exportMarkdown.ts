import { GraphIndex } from '../graph/graphQueries';
import type { Graph, GraphEdge, GraphNode } from '../types/graph';

const tag = (e: GraphEdge) => `${e.confidence}${e.resolution === 'resolved' ? '' : `, ${e.resolution}`}`;
const loc = (n: GraphNode) => (n.path ? `\`${n.path}:${n.startLine ?? 1}\`` : '_external_');
const bt = (s: string) => '`' + s.replace(/`/g, "'") + '`';
/** Table cells: a literal pipe would split the row. */
const cell = (s: string) => s.replace(/\|/g, '\\|');

/** Endpoint documentation: where each endpoint is defined, what handles it, what it touches and who calls it. Deterministic. */
export function exportMarkdown(graph: Graph): string {
  const idx = new GraphIndex(graph);
  const endpoints = graph.nodes
    .filter((n) => n.kind === 'api-endpoint')
    .sort((a, b) => String(a.metadata.path).localeCompare(String(b.metadata.path)) || String(a.metadata.method).localeCompare(String(b.metadata.method)) || a.id.localeCompare(b.id));
  const out: string[] = ['# API flow documentation', '', 'Generated by Codebase API Flow Explorer from static analysis. Confidence tags: `high` = direct source evidence, `medium`/`low` = inferred.', ''];

  const kinds = new Map<string, number>();
  for (const n of graph.nodes) kinds.set(n.kind, (kinds.get(n.kind) ?? 0) + 1);
  out.push('## Summary', '', `- Endpoints: ${endpoints.length}`, `- Graph: ${graph.nodes.length} nodes, ${graph.edges.length} edges`, `- Unresolved relationships: ${graph.edges.filter((e) => e.resolution === 'unresolved').length}`, '');
  if (endpoints.length) {
    out.push('| Method | Path | Framework | Defined in |', '| --- | --- | --- | --- |');
    for (const e of endpoints) out.push(`| ${cell(String(e.metadata.method))} | ${cell(bt(String(e.metadata.path)))} | ${cell(String(e.metadata.framework))} | ${cell(loc(e))} |`);
    out.push('');
  }

  out.push('## Endpoints', '');
  for (const e of endpoints) {
    out.push(`### ${e.metadata.method} ${bt(String(e.metadata.path))}`, '', `Defined in ${loc(e)} (${e.metadata.framework}).`, '');
    const out_ = idx.out(e.id);
    const handlers = out_.filter((x) => x.kind === 'handles-route');
    if (handlers.length) {
      out.push('**Handler**', '');
      for (const h of handlers) out.push(`- ${idx.nodes.get(h.target)?.qualifiedName ?? h.target} ${loc(idx.nodes.get(h.target)!)} (${tag(h)})`);
      out.push('');
    }
    const guards = out_.filter((x) => x.kind === 'uses-guard' || x.kind === 'uses-middleware');
    if (guards.length) {
      out.push('**Guards, middleware and interceptors**', '');
      for (const g of guards) out.push(`- ${g.kind === 'uses-guard' ? 'guard' : idx.nodes.get(g.target)?.kind}: ${idx.nodes.get(g.target)?.name} (${tag(g)}) — ${g.evidence.explanation}`);
      out.push('');
    }
    // downstream data access reached through the handler(s)
    const seen = new Set<string>();
    const data: string[] = [];
    const walk = (id: string, depth: number) => {
      if (depth > 6 || seen.has(id)) return;
      seen.add(id);
      for (const x of idx.out(id)) {
        if (x.kind === 'reads' || x.kind === 'writes' || x.kind === 'publishes') data.push(`- ${x.kind} ${idx.nodes.get(x.target)?.name} — ${x.evidence.path}:${x.evidence.line} (${tag(x)})`);
        else if (['calls', 'handles-route'].includes(x.kind)) walk(x.target, depth + 1);
      }
    };
    for (const h of handlers) walk(h.target, 0);
    if (data.length) out.push('**Data access**', '', ...[...new Set(data)].sort(), '');
    const callers = idx.in(e.id).filter((x) => x.kind === 'http-request');
    if (callers.length) {
      out.push('**Called from**', '');
      for (const c of callers) {
        const n = idx.nodes.get(c.source);
        out.push(`- ${n?.name} ${n ? loc(n) : ''} (${tag(c)})${c.reason ? ` — ${c.reason}` : ''}`);
      }
      out.push('');
    }
  }

  const unmatched = graph.edges.filter((e) => e.kind === 'http-request' && e.resolution === 'unresolved').sort((a, b) => a.id.localeCompare(b.id));
  if (unmatched.length) {
    out.push('## Requests without a matching endpoint', '');
    for (const e of unmatched) out.push(`- ${idx.nodes.get(e.source)?.name} ${loc(idx.nodes.get(e.source)!)} — ${e.reason ?? 'unresolved'}`);
    out.push('');
  }
  return out.join('\n');
}
